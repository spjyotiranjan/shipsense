"""Compare regenerated canonical artifacts without repairing the checked-in files."""

import os
import subprocess
import tempfile
from pathlib import Path


def main() -> int:
    root = Path(__file__).resolve().parents[1]
    with tempfile.TemporaryDirectory(prefix="shipsense-contracts-") as directory:
        schema = Path(directory) / "openapi.json"
        types = Path(directory) / "generated.ts"
        commands = [
            [
                "uv",
                "run",
                "--frozen",
                "--package",
                "shipsense-api",
                "python",
                "-m",
                "shipsense_api.export_openapi",
                "--output",
                str(schema),
            ],
            [
                "node",
                "node_modules/openapi-typescript/bin/cli.js",
                str(schema),
                "-o",
                str(types),
            ],
        ]
        for command in commands:
            if subprocess.run(command, cwd=root, check=False).returncode:
                print("CONTRACT_GENERATION_FAILED")
                return 2
        expected = [
            (schema, root / "packages/contracts/openapi.json"),
            (types, root / "packages/contracts/src/generated.ts"),
        ]
        drift = [
            str(target.relative_to(root))
            for generated, target in expected
            if not target.is_file() or generated.read_bytes() != target.read_bytes()
        ]
        if drift:
            print("CONTRACT_DRIFT: " + ", ".join(drift))
            return 1
    print("Canonical OpenAPI and TypeScript match regenerated bytes.")
    return 0


if __name__ == "__main__":
    os.chdir(Path(__file__).resolve().parents[1])
    raise SystemExit(main())
